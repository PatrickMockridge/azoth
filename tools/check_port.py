#!/usr/bin/env python3
"""Refuse a spec that does not name its NeqSim source.

The port law in `AGENTS.md`: every id, equation, input, output, algorithm parameter and
constant names a NeqSim class and member at a pinned commit, a publication NeqSim cites,
or `caller`. This check reads `specs/models/**` and `specs/calcs/**` and refuses:

* a spec with no `source.neqsim`;
* a `source.neqsim.class` absent from the class index at its stated pin;
* a declared input or output the `[provenance]` table does not cover;
* an `[algorithm]`/`[solver]` leaf with no provenance entry;
* a `[[provenance.constants]]` row with no source.

The class index is `data/neqsim/classes.toml`, generated by `tools/gen_neqsim_classes.py`
from a pinned checkout or jar. CI has no JVM, so the index is committed.

    python tools/check_port.py            # check the tree
    python tools/check_port.py --root DIR  # check a fixture tree
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from collections.abc import Iterator
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "data" / "neqsim" / "classes.toml"


def pins(path: Path = INDEX) -> dict[str, set[str]]:
    """Each pin's class names, keyed by its short hash and its full commit."""
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    out: dict[str, set[str]] = {}
    for pin in data.get("pin", []):
        classes = {str(name) for name in pin.get("classes", [])}
        out[str(pin["short"])] = classes
        out[str(pin["commit"])] = classes
    return out


def specs(root: Path = ROOT) -> Iterator[tuple[Path, dict[str, Any]]]:
    """Every model and calc spec under a root, as (path, document)."""
    for tree in ("models", "calcs"):
        for path in sorted((root / "specs" / tree).rglob("*.toml")):
            yield path, tomllib.loads(path.read_text(encoding="utf-8"))


def leaves(mapping: dict[str, Any], prefix: str = "") -> set[str]:
    """Every non-table leaf of a nested block, keyed by its dotted path."""
    out: set[str] = set()
    for key, value in mapping.items():
        name = f"{prefix}{key}"
        if isinstance(value, dict):
            out |= leaves(value, f"{name}.")
        else:
            out.add(name)
    return out


def check_neqsim(spec: dict[str, Any], index: dict[str, set[str]]) -> list[str]:
    source = spec.get("source") or {}
    neqsim = source.get("neqsim")
    if not isinstance(neqsim, dict):
        return ["no `source.neqsim`: the port must name its NeqSim class, members and pin"]
    problems: list[str] = []
    class_name = str(neqsim.get("class", ""))
    commit = str(neqsim.get("commit", ""))
    known = index.get(commit) or index.get(commit[:7])
    if known is None:
        problems.append(f"`source.neqsim.commit` {commit!r} is not an indexed NeqSim pin")
    elif class_name not in known:
        problems.append(f"`source.neqsim.class` {class_name!r} is not a class at pin {commit}")
    members = neqsim.get("members") or []
    if not members:
        problems.append("`source.neqsim.members` is empty")
    for member in members:
        member = str(member)
        if "." in member:
            owner = member.split(".", 1)[0]
            if known is not None and owner not in known and owner != class_name:
                problems.append(
                    f"`source.neqsim.members` names {member!r}, whose class "
                    f"{owner!r} is not indexed"
                )
    return problems


def check_values(spec: dict[str, Any]) -> list[str]:
    provenance = spec.get("provenance")
    if not isinstance(provenance, dict):
        return ["no `[provenance]` table"]
    problems: list[str] = []
    for group in ("inputs", "outputs"):
        declared = set((spec.get(group) or {}).keys())
        table = provenance.get(group)
        if not isinstance(table, dict):
            problems.append(f"`[provenance.{group}]` is absent")
            continue
        overrides = set((table.get("overrides") or {}).keys())
        if not table.get("default") and (declared - overrides):
            missing = sorted(declared - overrides)
            problems.append(f"`[provenance.{group}]` has no default and no row for {missing}")
        extra = sorted(overrides - declared)
        if extra:
            problems.append(f"`[provenance.{group}.overrides]` names undeclared {extra}")
        for name, entry in (table.get("overrides") or {}).items():
            if not isinstance(entry, dict) or not entry.get("source"):
                problems.append(f"`[provenance.{group}.overrides.{name}]` has no source")

    algorithm = spec.get("algorithm") or spec.get("solver") or {}
    covered = set((provenance.get("algorithm") or {}).keys())
    missing = sorted(leaves(algorithm) - covered)
    if missing:
        problems.append(f"`[provenance.algorithm]` has no row for {missing}")
    for name, entry in (provenance.get("algorithm") or {}).items():
        if not isinstance(entry, dict) or not entry.get("source"):
            problems.append(f"`[provenance.algorithm.{name}]` has no source")

    for row in provenance.get("constants") or []:
        if not isinstance(row, dict):
            problems.append("a `[[provenance.constants]]` row is not a table")
            continue
        for key in ("name", "value", "source"):
            if key not in row:
                problems.append(f"a `[[provenance.constants]]` row has no {key!r}")
    return problems


def check(root: Path = ROOT) -> list[str]:
    index = pins(root / "data" / "neqsim" / "classes.toml")
    problems: list[str] = []
    for path, spec in specs(root):
        relative = path.relative_to(root)
        for problem in check_neqsim(spec, index) + check_values(spec):
            problems.append(f"{relative}: {problem}")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args()
    problems = check(args.root)
    if problems:
        for problem in problems:
            print(f"  ERROR  {problem}", file=sys.stderr)
        print(f"check_port: FAILED with {len(problems)} problem(s)", file=sys.stderr)
        return 1
    print("check_port: OK (every spec names its NeqSim source and every value its provenance)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
