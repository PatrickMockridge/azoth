#!/usr/bin/env python3
"""Generate the NeqSim class index `data/neqsim/classes.toml`.

`tools/check_port.py` refuses a spec whose `source.neqsim.class` is not a class at its
stated pin. CI has no JVM and no NeqSim checkout, so the index is committed; this tool
regenerates it from a checkout or a jar when a pin moves.

A pin is given as `SHORT:COMMIT:PATH`, where PATH is a NeqSim checkout root or a jar:

    python tools/gen_neqsim_classes.py \\
        --pin b40bb11:b40bb1134508faa24b07aed9a23c4d52865e5c2a:git:/tmp/neqsim-pin \\
        --pin f0c7436:f0c7436c6923766b1e22957b7075f650600457a7:validation/neqsim/neqsim-f0c7436.jar

    python tools/gen_neqsim_classes.py --check --pin ...

The index lists class names only. The member names a spec states are checked for shape and
class ownership by `check_port`; proving every method exists needs the source blobs, which
is the kind of check the capture and the differential oracle make.

A second index, `data/neqsim/port_scope.toml`, covers the three physics trees only and
carries the facts the port inventory needs: each class's package, kind, line count and
the NeqSim classes it references. It needs the source, so it is generated from a checkout
or a git commit, never a jar:

    python tools/gen_neqsim_classes.py --scope \\
        --pin b40bb11:b40bb1134508faa24b07aed9a23c4d52865e5c2a:git:/tmp/neqsim-pin

    python tools/gen_neqsim_classes.py --scope --check --pin ...
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "neqsim" / "classes.toml"
SCOPE_OUT = ROOT / "data" / "neqsim" / "port_scope.toml"

HEADER = """\
# GENERATED FILE - DO NOT EDIT BY HAND.
#
# Generated by `tools/gen_neqsim_classes.py` from a pinned NeqSim checkout or jar.
# Each pin lists the class names at that commit; `tools/check_port.py` refuses a spec
# whose `source.neqsim.class` is not in the list for the pin it states.
"""

#: The physics trees the port inventory covers. `process/` is carried by unit operation in
#: ROADMAP.md; `fluidmechanics/` and the support packages are not targets. `pvtsimulation`
#: is included because the wax, asphaltene and flow-assurance work lives there.
PHYSICS_TREES = (
    "src/main/java/neqsim/thermo",
    "src/main/java/neqsim/thermodynamicoperations",
    "src/main/java/neqsim/physicalproperties",
    "src/main/java/neqsim/pvtsimulation",
)

SCOPE_HEADER = """\
# GENERATED FILE - DO NOT EDIT BY HAND.
#
# Generated by `tools/gen_neqsim_classes.py --scope` from a pinned NeqSim checkout or
# commit. One row per class in thermo/, thermodynamicoperations/, physicalproperties/ and
# pvtsimulation/: its package, kind, line count and the NeqSim classes it names.
# `tools/check_port_backlog` holds the inventory's size metric to this file.
"""


def from_checkout(path: Path) -> set[str]:
    root = path / "src" / "main" / "java"
    if not root.is_dir():
        sys.exit(f"gen_neqsim_classes: {path} has no src/main/java")
    names: set[str] = set()
    for source in root.rglob("*.java"):
        stem = source.stem
        if stem in ("package-info", "module-info"):
            continue
        names.add(stem)
    return names


def from_git(repo: Path, commit: str) -> set[str]:
    """Class names from a commit's tree, without checking out its blobs."""
    result = subprocess.run(
        ["git", "-C", str(repo), "ls-tree", "-r", "--name-only", commit, "--", "src/main/java"],
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        sys.exit(f"gen_neqsim_classes: git could not list {commit} in {repo}: {result.stderr}")
    names: set[str] = set()
    for line in result.stdout.splitlines():
        source = Path(line)
        if source.suffix != ".java" or source.stem in ("package-info", "module-info"):
            continue
        names.add(source.stem)
    return names


def from_jar(path: Path) -> set[str]:
    names: set[str] = set()
    with zipfile.ZipFile(path) as archive:
        for entry in archive.namelist():
            if not entry.endswith(".class"):
                continue
            stem = Path(entry).stem.split("$", 1)[0]
            if stem in ("package-info", "module-info"):
                continue
            names.add(stem)
    return names


def _strip_java(text: str) -> str:
    """Source with comments and literals removed, so a scan sees names and not prose."""
    out: list[str] = []
    i = 0
    while i < len(text):
        pair = text[i : i + 2]
        if pair == "//":
            end = text.find("\n", i)
            i = len(text) if end < 0 else end
            continue
        if pair == "/*":
            end = text.find("*/", i + 2)
            i = len(text) if end < 0 else end + 2
            continue
        if text[i] in ('"', "'"):
            quote = text[i]
            i += 1
            while i < len(text):
                if text[i] == "\\":
                    i += 2
                    continue
                if text[i] == quote:
                    i += 1
                    break
                i += 1
            out.append(" ")
            continue
        out.append(text[i])
        i += 1
    return "".join(out)


def _kind(name: str, stripped: str) -> str:
    match = re.search(rf"\b(interface|enum|abstract\s+class|class)\s+{re.escape(name)}\b", stripped)
    if match is None:
        return "class"
    kind = re.sub(r"\s+", " ", match.group(1))
    return "abstract" if kind == "abstract class" else kind


def _scope_entry(path: str, text: str, universe: set[str]) -> dict[str, object]:
    name = Path(path).stem
    relative = path.split("src/main/java/", 1)[-1]
    package = relative.rsplit("/", 1)[0].replace("/", ".")
    stripped = _strip_java(text)
    refs = sorted(
        {
            token
            for token in re.findall(r"\b[A-Z][A-Za-z0-9_]*\b", stripped)
            if token in universe and token != name
        }
    )
    return {
        "name": name,
        "package": package,
        "kind": _kind(name, stripped),
        "loc": len(text.splitlines()),
        "refs": refs,
    }


def _physics_paths_git(repo: Path, commit: str) -> list[str]:
    result = subprocess.run(
        ["git", "-C", str(repo), "ls-tree", "-r", "--name-only", commit, "--", *PHYSICS_TREES],
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        sys.exit(f"gen_neqsim_classes: git could not list {commit} in {repo}: {result.stderr}")
    return [
        line
        for line in result.stdout.splitlines()
        if line.endswith(".java") and Path(line).stem not in ("package-info", "module-info")
    ]


def _git_file(repo: Path, commit: str, path: str) -> str:
    result = subprocess.run(
        ["git", "-C", str(repo), "show", f"{commit}:{path}"], capture_output=True, check=False
    )
    if result.returncode != 0:
        sys.exit(f"gen_neqsim_classes: git could not read {path} at {commit}: {result.stderr}")
    return result.stdout.decode("utf-8", errors="replace")


def _physics_paths_checkout(path: Path) -> list[str]:
    base = path / "src" / "main" / "java"
    if not base.is_dir():
        sys.exit(f"gen_neqsim_classes: {path} has no src/main/java")
    paths: list[str] = []
    for tree in (
        "neqsim/thermo",
        "neqsim/thermodynamicoperations",
        "neqsim/physicalproperties",
        "neqsim/pvtsimulation",
    ):
        for source in sorted((base / tree).rglob("*.java")):
            if source.stem in ("package-info", "module-info"):
                continue
            paths.append(source.relative_to(path).as_posix())
    return paths


def scope_from_git(repo: Path, commit: str) -> tuple[str, list[dict[str, object]]]:
    universe = from_git(repo, commit)
    return commit, [
        _scope_entry(path, _git_file(repo, commit, path), universe)
        for path in _physics_paths_git(repo, commit)
    ]


def scope_from_checkout(path: Path) -> tuple[str, list[dict[str, object]]]:
    universe = from_checkout(path)
    return "", [
        _scope_entry(relative, (path / relative).read_text(encoding="utf-8"), universe)
        for relative in _physics_paths_checkout(path)
    ]


def render_scope(commit: str, entries: list[dict[str, object]]) -> str:
    lines = [SCOPE_HEADER]
    if commit:
        lines.append(f'commit = "{commit}"')
        lines.append("")
    for entry in sorted(entries, key=lambda item: str(item["name"])):
        lines.append("[[class]]")
        lines.append(f'name = "{entry["name"]}"')
        lines.append(f'package = "{entry["package"]}"')
        lines.append(f'kind = "{entry["kind"]}"')
        lines.append(f"loc = {entry['loc']}")
        refs = ", ".join(json.dumps(name) for name in entry["refs"])  # type: ignore[arg-type]
        lines.append(f"refs = [{refs}]")
        lines.append("")
    return "\n".join(lines)


def render(pins: list[tuple[str, str, set[str]]]) -> str:
    lines = [HEADER]
    for short, commit, classes in sorted(pins, key=lambda pin: pin[0]):
        lines.append("[[pin]]")
        lines.append(f'short = "{short}"')
        lines.append(f'commit = "{commit}"')
        lines.append("classes = [")
        for name in sorted(classes):
            lines.append(f'    "{name}",')
        lines.append("]")
        lines.append("")
    return "\n".join(lines)


def _pin(value: str) -> tuple[str, str, str]:
    short, separator, rest = value.partition(":")
    commit, separator2, path = rest.partition(":")
    if not separator or not separator2 or not short or not commit or not path:
        sys.exit(f"gen_neqsim_classes: --pin {value!r} is not SHORT:COMMIT:PATH")
    return short, commit, path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--pin",
        action="append",
        required=True,
        metavar="SHORT:COMMIT:PATH",
        help="a pin's short hash, full commit and checkout-or-jar path",
    )
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--scope", action="store_true", help="write the physics-tree scope index")
    parser.add_argument("--scope-out", type=Path, default=SCOPE_OUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    if args.scope:
        if len(args.pin) != 1:
            sys.exit("gen_neqsim_classes: --scope takes exactly one --pin")
        _, commit, path = _pin(args.pin[0])
        if path.startswith("git:"):
            commit, entries = scope_from_git(Path(path[4:]), commit)
        elif Path(path).suffix == ".jar":
            sys.exit("gen_neqsim_classes: --scope needs source, and a jar carries none")
        else:
            commit, entries = scope_from_checkout(Path(path))
        content = render_scope(commit, entries)
        if args.check:
            current = args.scope_out.read_text(encoding="utf-8") if args.scope_out.exists() else ""
            if current != content:
                sys.exit(
                    f"gen_neqsim_classes: {args.scope_out.relative_to(ROOT)} is out of date - "
                    "run `python tools/gen_neqsim_classes.py --scope`"
                )
            print("gen_neqsim_classes: the port scope is current")
            return 0
        args.scope_out.parent.mkdir(parents=True, exist_ok=True)
        args.scope_out.write_text(content, encoding="utf-8")
        print(
            f"gen_neqsim_classes: wrote {args.scope_out.relative_to(ROOT)} "
            f"({len(entries)} physics classes)"
        )
        return 0

    pins: list[tuple[str, str, set[str]]] = []
    for value in args.pin:
        short, commit, path = _pin(value)
        if path.startswith("git:"):
            classes = from_git(Path(path[4:]), commit)
        else:
            source = Path(path)
            classes = from_jar(source) if source.suffix == ".jar" else from_checkout(source)
        pins.append((short, commit, classes))

    content = render(pins)
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if current != content:
            sys.exit(
                f"gen_neqsim_classes: {args.out.relative_to(ROOT)} is out of date - "
                "run `python tools/gen_neqsim_classes.py`"
            )
        print("gen_neqsim_classes: the class index is current")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(content, encoding="utf-8")
    print(f"gen_neqsim_classes: wrote {args.out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
