#!/usr/bin/env python3
"""Generate the generated-record crates' `CalcResult` blocks.

Every `crates/azoth-process/src/models/*.rs` and `crates/azoth-pvt/src/*.rs` carries one
`impl CalcResult for <Struct>`: a `CALC_ID`, a `FIELDS` list and the `warnings` accessor. None
of it is a decision - the id is the spec's own, the fields are the struct's `pub` fields in
declaration order, and the accessor is the one field every result has.

    python tools/gen_rust_model_records.py            # write
    python tools/gen_rust_model_records.py --check    # fail if the tree is not what this emits
    python tools/gen_rust_model_records.py --survey   # what it covers, and what it leaves

The structs and the kernels stay where they are: `tools/provenance.py` derives each kernel's Rust
path from the file it sits in, so moving a struct breaks
`test_every_registered_id_resolves_to_its_spec_and_kernels`. Only the block moves.

The crates whose blocks are generated are named here. The others hand-write their `impl`s in
`results.rs`; a crate added to this map has its blocks removed from its kernel first, which is
what the seed-then-remove step in the generator chain is for.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import rust_index

ROOT = Path(__file__).resolve().parent.parent

#: Crate -> the module prefix its model structs are reachable through. The process crate keeps
#: its models under `src/models/`; the pvt crate is flat.
GENERATED = {
    "azoth-process": "crate::models",
    "azoth-pvt": "crate",
}

#: The field every result carries, and the accessor `CalcResult` asks for.
WARNINGS = "warnings"

HEADER = """//! The {title} models' `CalcResult` blocks, emitted from the specs and the structs.
//!
//! Generated by `tools/gen_rust_model_records.py` - **do not edit by hand.** Each block is a
//! function of two declarations that already exist: `CALC_ID` is the spec's own id and `FIELDS`
//! is the struct's `pub` fields in declaration order, which is what
//! `test_registry_contract` holds the published result to.
//!
//! The structs and the kernels stay in {where}: `tools/provenance.py` derives a kernel's
//! Rust path from the file it sits in, so producing them here would break
//! `test_every_registered_id_resolves_to_its_spec_and_kernels`.

use azoth_core::{{CalcResult, Warning}};

"""


def struct_name(result: rust_index.ResultType) -> str:
    """The struct this block is written for, the last segment of its item path."""
    return result.item_path.rpartition("::")[2]


def crate_of(result: rust_index.ResultType) -> str:
    """The crate the result's struct sits in, from the file it lives in."""
    return result.module_file.relative_to(ROOT / "crates").parts[0]


def module_path(result: rust_index.ResultType) -> str:
    """The struct's module, from the crate's prefix and its file's stem."""
    return f"{GENERATED[crate_of(result)]}::{result.module_file.stem}"


def output_path(crate: str) -> Path:
    """Where the crate's generated blocks live."""
    return ROOT / "crates" / crate / "src" / "model_records_gen.rs"


def emit_block(result: rust_index.ResultType) -> str:
    """One `impl CalcResult` block."""
    name = struct_name(result)
    fields = [field for field, _ in result.fields]
    if fields[-1] != WARNINGS:
        raise ValueError(f"{result.calc_id}: last field is {fields[-1]!r}, not `{WARNINGS}`")
    body = "\n".join(f'        "{field}",' for field in fields)
    return (
        f"impl CalcResult for {name} {{\n"
        f'    const CALC_ID: &\'static str = "{result.calc_id}";\n'
        f"    const FIELDS: &'static [&'static str] = &[\n"
        f"{body}\n"
        f"    ];\n"
        f"\n"
        f"    fn warnings(&self) -> &[Warning] {{\n"
        f"        &self.{WARNINGS}\n"
        f"    }}\n"
        f"}}\n"
    )


def crate_results(crate: str) -> tuple[list[rust_index.ResultType], list[str]]:
    """`(covered, refused)` - the crate's ids this can write a block for, and why not."""
    covered, left = [], []
    for result in rust_index.result_types():
        if crate_of(result) != crate:
            continue
        try:
            fields = [field for field, _ in result.fields]
            if not fields or fields[-1] != WARNINGS:
                raise ValueError(f"last field is {fields[-1] if fields else None!r}")
        except ValueError as why:
            left.append(f"{result.calc_id}: {why}")
            continue
        covered.append(result)
    return covered, left


def emit(crate: str) -> str:
    """One crate's whole file: a header, the imports, and one block per covered id."""
    covered, _ = crate_results(crate)
    imports = "\n".join(f"use {module_path(r)}::{struct_name(r)};" for r in covered)
    blocks = "\n".join(emit_block(r) for r in covered)
    where = "`models/*.rs`" if crate == "azoth-process" else "`<id>.rs`"
    title = crate.removeprefix("azoth-")
    header = HEADER.format(title=title, where=where)
    return f"{header}{imports}\n\n\n{blocks}"


def rustfmt(text: str) -> str:
    """Rustfmt's own output, refused rather than fallen back on (`gen_palette`'s policy)."""
    done = subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout"],
        input=text,
        capture_output=True,
        text=True,
        check=False,
    )
    if done.returncode != 0:
        raise SystemExit(f"rustfmt failed: {done.stderr}")
    return done.stdout


def generated_crates() -> list[str]:
    """The crates that have at least one result, in the map's own order."""
    present = {crate_of(result) for result in rust_index.result_types()}
    return [crate for crate in GENERATED if crate in present]


def main() -> int:
    if "--survey" in sys.argv:
        for crate in generated_crates():
            covered, left = crate_results(crate)
            print(f"{crate}: covered {len(covered)}")
            for why in left:
                print(f"   left hand-written: {why}")
        return 0

    failed = False
    for crate in generated_crates():
        text = rustfmt(emit(crate))
        path = output_path(crate)
        if "--check" in sys.argv:
            current = path.read_text() if path.exists() else ""
            if current != text:
                print(f"::error::{path.relative_to(ROOT)} is not what the generator emits")
                failed = True
            continue
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
