#!/usr/bin/env python3
"""Render `PORT.md` from `databank/port_backlog.toml` and the tree.

A package row is checked when every class it names is named by a spec; a data column is
listed while its manifest reason is `not-ported`. The work rows are ordered by the tier
order, then S/M/L, and grouped into batches whose summed line count is at most 1,500.

    python tools/gen_port_checklist.py
    python tools/gen_port_checklist.py --check
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import port_backlog as backlog

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "PORT.md"
BATCH_LOC = 1500
SIZE_ORDER = {"S": 0, "M": 1, "L": 2}


def done(row: dict, covered: set[str]) -> bool:
    classes = [str(name) for name in row.get("classes", [])]
    return bool(classes) and all(name in covered for name in classes)


def covered_count(row: dict, covered: set[str]) -> int:
    return sum(1 for name in row.get("classes", []) if str(name) in covered)


def render(root: Path = ROOT) -> str:
    data = backlog.read(root / backlog.BACKLOG_REL)
    rows = list(data.get("package", [])) + list(data.get("process", []))
    covered = backlog.spec_classes(root)
    columns = backlog.manifest_not_ported(root)

    unclassified = [row for row in rows if not isinstance(row.get("tier"), int) or row["tier"] < 0]
    if unclassified:
        names = ", ".join(str(row.get("id")) for row in unclassified)
        raise SystemExit(f"gen_port_checklist: unclassified rows: {names}")

    work = [row for row in rows if row.get("state") == "port" and not row.get("blocked_by")]
    blocked = [row for row in rows if row.get("state") == "port" and row.get("blocked_by")]
    other = [row for row in rows if row.get("state") != "port"]

    open_rows = [row for row in work if not done(row, covered)]
    finished = [row for row in work if done(row, covered)]
    open_rows.sort(key=lambda row: (int(row["tier"]), SIZE_ORDER.get(row["size"], 9), row["id"]))

    batches: list[list[dict]] = []
    current: list[dict] = []
    total = 0
    for row in open_rows:
        loc = int(row.get("loc", 0))
        same_tier = bool(current) and current[0]["tier"] == row["tier"]
        if current and (not same_tier or total + loc > BATCH_LOC or loc > BATCH_LOC):
            batches.append(current)
            current = []
            total = 0
        current.append(row)
        total += loc
        if loc > BATCH_LOC:
            batches.append(current)
            current = []
            total = 0
    if current:
        batches.append(current)

    lines = [
        "# Port checklist",
        "",
        "Generated by `tools/gen_port_checklist.py` from `databank/port_backlog.toml`.",
        "Do not edit. A row is checked when every class it names is named by a spec.",
        "",
        f"- open rows: {len(open_rows)}",
        f"- open classes: {sum(len(row.get('classes', [])) for row in open_rows)}",
        f"- remaining not-ported columns: {len(columns)}",
        "",
    ]

    position: dict[int, int] = {}
    for batch in batches:
        tier = int(batch[0]["tier"])
        position[tier] = position.get(tier, 0) + 1
        loc = sum(int(row.get("loc", 0)) for row in batch)
        lines.append(f"## Tier {tier} — batch {tier}.{position[tier]} ({loc} loc)")
        lines.append("")
        for row in batch:
            count = covered_count(row, covered)
            total_classes = len(row.get("classes", []))
            progress = f" ({count}/{total_classes} covered)" if count else ""
            flags = " [solver]" if row.get("new_solver") else ""
            names = ", ".join(f"`{name}`" for name in row.get("classes", []))
            lines.append(
                f"- [ ] [{row.get('size', '?')}]{flags} {row.get('title')} — {names}{progress}"
            )
        lines.append("")

    if finished:
        lines.extend(["## Done", ""])
        for row in sorted(finished, key=lambda item: (int(item["tier"]), item["id"])):
            lines.append(f"- [x] {row.get('title')} — {len(row.get('classes', []))} classes")
        lines.append("")

    if blocked:
        lines.extend(["## Blocked", ""])
        for row in blocked:
            names = ", ".join(f"`{name}`" for name in row.get("classes", []))
            lines.append(f"- [ ] {row.get('title')} — {names} — {row.get('blocked_by')}")
        lines.append("")

    if other:
        lines.extend(
            ["## Not work", "", "No checkbox: these classes are plumbing, dead, or excluded.", ""]
        )
        for state in ("internal", "unreachable", "excluded"):
            members = [row for row in other if row.get("state") == state]
            if not members:
                continue
            count = sum(len(row.get("classes", [])) for row in members)
            lines.append(f"### {state} — {count} classes")
            for row in sorted(members, key=lambda item: (int(item["tier"]), item["id"])):
                reason = f" — {row.get('blocked_by')}" if row.get("blocked_by") else ""
                lines.append(
                    f"- {row.get('title')} ({len(row.get('classes', []))} classes){reason}"
                )
            lines.append("")

    if columns:
        lines.extend(["## Data columns", ""])
        for column in columns:
            source = (
                f" `{column['class']}`"
                if column["class"] and column["class"] != column["column"]
                else ""
            )
            lines.append(f"- [ ] {column['file']}.{column['column']}{source}")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args()
    content = render()
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if current != content:
            print(
                f"gen_port_checklist: {args.out.relative_to(ROOT)} is out of date - "
                "run `python tools/gen_port_checklist.py`",
                file=sys.stderr,
            )
            return 1
        print("gen_port_checklist: the checklist is current")
        return 0
    args.out.write_text(content, encoding="utf-8")
    print(f"gen_port_checklist: wrote {args.out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
